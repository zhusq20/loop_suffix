"""Render final tables from the frozen suites' measurements (no inference)."""
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAT = ROOT/'results/loopfill-latency512-20261107'
TP = ROOT/'results/loopfill-table2-20261107-v2'
MODELS = ['huginn-3.5b','ouro-1.4b','ouro-2.6b']
DATASETS = ['gsm8k','math500','bbh','humanevalplus','mbppplus','specbench']
NAMES = ['GSM8K','MATH-500','BBH','HumanEval+','MBPP+','SpecBench']
ARMS = ['ar','wavefront','loopspec-dual','budget-suffix','budget-online']
LABELS = ['AR','WFD','LoopSpec','Suffix-only','LoopFill-online']

def render(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |','| '+' | '.join(['---']*len(headers))+' |']+['| '+' | '.join(row)+' |' for row in rows])

def main():
    lat = list(csv.DictReader((LAT/'measurements.csv').open()))
    tp = list(csv.DictReader((TP/'measurements.csv').open()))
    assert len(lat)==90 and all(r['outcome']=='complete' for r in lat)
    assert sum(int(r['completed_requests']) for r in lat)==31380
    assert len(tp)==75 and sum(r['outcome']=='complete' for r in tp)==74
    assert [(r['model'],r['batch'],r['arm']) for r in tp if r['outcome']!='complete']==[('huginn-3.5b','16','wavefront')]
    idx = {(r['model'],r['dataset'],r['arm']):r for r in lat}
    tidx = {(r['model'],r['batch'],r['arm']):r for r in tp}
    first = ['# Table 1 — B=1 decode latency speedup and acceptance length','',
        '90/90 cells complete; 31,380 requests. Each entry is latency speedup vs AR × / loop-normalized γ. Up to 512 new tokens; decode-only timing; one repeat. GM is the unweighted geometric mean of the six dataset speedups.','']
    second = ['# Table 2 — SpecBench end-to-end output throughput','',
        '74 complete cells and one observed OOM; 480 requests per complete cell, up to 1024 new tokens. Entries are output token/s (speedup vs same-model, same-batch AR). Timing includes prefill, decode, scheduling and local persistence; one repeat.','']
    tex1=[]; tex2=[]
    for m in MODELS:
        rows=[]; texrows=[]
        for a,label in zip(ARMS,LABELS):
            vals=[idx[m,d,a] for d in DATASETS]
            gm=math.exp(sum(math.log(float(r['latency_speedup'])) for r in vals)/6)
            cells=[f"{float(r['latency_speedup']):.2f} / {float(r['gamma']):.2f}" for r in vals]
            rows.append([label]+cells+[f'{gm:.2f}'])
            texrows.append(' & '.join([label]+cells+[f'{gm:.2f}'])+r' \\')
        first += ['## '+m,'',render(['Method']+NAMES+['GM speedup'],rows),'']
        tex1 += ['% '+m,r'\begin{tabular}{lrrrrrrr}',r'\hline',' & '.join(['Method']+NAMES+['GM'])+r' \\',r'\hline']+texrows+[r'\hline',r'\end{tabular}','']
        rows=[]; texrows=[]
        for a,label in zip(ARMS,LABELS):
            cells=[]
            for b in ['1','2','4','8','16']:
                r=tidx[m,b,a]
                if r['outcome']=='oom': cells.append('OOM'); continue
                val=float(r['output_tput']); base=float(tidx[m,b,'ar']['output_tput'])
                assert int(r['requests'])==480
                cells.append(f'{val:.2f} ({val/base:.2f}×)')
            rows.append([label]+cells)
            texrows.append(' & '.join([label]+[c.replace('×',r'$\times$') for c in cells])+r' \\')
        second += ['## '+m,'',render(['Method','B1','B2','B4','B8','B16'],rows),'']
        tex2 += ['% '+m,r'\begin{tabular}{lrrrrr}',r'\hline',r'Method & B1 & B2 & B4 & B8 & B16 \\',r'\hline']+texrows+[r'\hline',r'\end{tabular}','']
    caveat='BF16, greedy, CUDA Graph off, same-engine baselines. Outputs can differ between methods: speedup is not proof of equal output or task quality. No confidence intervals are inferred from this single timing repeat. The two tables use different output caps and timing boundaries and must not be pooled.'
    (LAT/'table1.md').write_text('\n'.join(first)+caveat+'\n')
    (TP/'table2-final.md').write_text('\n'.join(second)+caveat+'\n')
    for name,lines in [('table1-latency512.tex',tex1),('table2-throughput.tex',tex2)]:
        (ROOT/'paper/tables'/name).write_text('% Generated by scripts/loop_final_tables.py; see Markdown tables for protocol and caveats.\n'+'\n'.join(lines))
    print('Rendered 90 latency cells and 75 throughput outcomes to Markdown and LaTeX.')

if __name__=='__main__': main()
