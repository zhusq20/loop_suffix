"""Render temperature=1 latency and candidate-coverage tables without inference."""
import csv
import math

from loop_final_tables import ARMS, DATASETS, LABELS, MODELS, NAMES, ROOT, render


def main():
    directory = ROOT / 'results/loopfill-latency512-t1-20261108'
    rows = list(csv.DictReader((directory / 'measurements.csv').open()))
    assert len(rows) == 90 and all(r['outcome'] == 'complete' for r in rows)
    assert sum(int(r['completed_requests']) for r in rows) == 31380
    index = {(r['model'], r['dataset'], r['arm']): r for r in rows}
    assert len(index) == 90
    latency = ['# Table 1 — Temperature=1 latency speedup and acceptance length', '',
        '90/90 cells complete; 31,380 requests. Each entry is latency speedup vs AR × / '
        'loop-normalized γ. B=1, up to 512 new tokens, decode-only timing, one repeat; '
        'temperature=1, top_p=1, no top-k truncation, sampling seed=0. '
        'GM is the unweighted geometric mean of six dataset speedups.', '']
    coverage = ['# Temperature=1 candidate coverage', '',
        'Each entry is the pooled percentage of sampled full-depth decode tokens that hit '
        'existing draft candidates. Prefill tokens are excluded. AR has no drafts. '
        'This is not accepted nodes / created nodes, a proposal acceptance probability, '
        'or a measurement of saved computation.', '']
    tex = ['% Generated by scripts/loop_temperature_table.py; see Markdown for protocol/caveats.']
    for model in MODELS:
        speed_rows, hit_rows, tex_rows = [], [], []
        for arm, label in zip(ARMS, LABELS):
            values = [index[model, dataset, arm] for dataset in DATASETS]
            gm = math.exp(sum(math.log(float(v['latency_speedup'])) for v in values) / 6)
            cells = [f"{float(v['latency_speedup']):.2f} / {float(v['gamma']):.2f}"
                     for v in values]
            speed_rows.append([label, *cells, f'{gm:.2f}'])
            hit_rows.append([label, *[f"{100 * float(v['pooled_acceptance_rate']):.2f}%"
                                      for v in values]])
            tex_rows.append(' & '.join([label, *cells, f'{gm:.2f}']) + r' \\')
        latency += ['## ' + model, '', render(['Method', *NAMES, 'GM speedup'], speed_rows), '']
        coverage += ['## ' + model, '', render(['Method', *NAMES], hit_rows), '']
        tex += ['% ' + model, r'\begin{tabular}{lrrrrrrr}', r'\hline',
                ' & '.join(['Method', *NAMES, 'GM']) + r' \\', r'\hline',
                *tex_rows, r'\hline', r'\end{tabular}', '']
    caveat = ('BF16, CUDA Graph off, same-engine baselines. Shared request/position random '
        'numbers do not guarantee identical outputs across different BF16 compute shapes. '
        'Single timing repeat and one sampling seed: no latency confidence intervals or '
        'task-quality claims. This batch is separate from temperature=0 results.')
    (directory / 'table1.md').write_text('\n'.join(latency) + caveat + '\n')
    (directory / 'candidate-hit-rates.md').write_text('\n'.join(coverage) + caveat + '\n')
    (ROOT / 'paper/tables/table1-latency512-t1.tex').write_text('\n'.join(tex))
    print('Rendered 90 temperature=1 cells to Markdown and LaTeX.')


if __name__ == '__main__':
    main()
